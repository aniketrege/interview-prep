"""Execute every solution notebook and syntax-check every practice template.

    python tools/verify.py                      # everything
    python tools/verify.py P_pytorch            # one part
    python tools/verify.py G1_systems/solutions/G1.03_memory_math.ipynb

Solutions are executed in place (outputs saved, so you can read reference
results without re-running). Results are merged into VERIFICATION.md.
Templates are not executed (they raise NotImplementedError by design);
each code cell is compiled to catch syntax errors and stray solution code.
"""
from __future__ import annotations

import ast
import fcntl
import os
import datetime as dt
import json
import re
import sys
import time
from pathlib import Path

import nbformat
from nbclient import NotebookClient
from nbclient.exceptions import CellExecutionError

REPO = Path(__file__).resolve().parent.parent
PARTS = ["P_pytorch", "A_coding", "G1_systems"]
STATE = REPO / "tools" / "verification.json"
REPORT = REPO / "VERIFICATION.md"


def env_line() -> str:
    import torch

    gpu = torch.cuda.get_device_name(0) if torch.cuda.is_available() else "cpu"
    return f"torch {torch.__version__}, {gpu} x{torch.cuda.device_count()}, python {sys.version.split()[0]}"


def strip_magics(src: str) -> str:
    return "\n".join("pass" if l.lstrip().startswith(("%", "!")) else l for l in src.splitlines())


def check_template(path: Path) -> str | None:
    nb = nbformat.read(path, as_version=4)
    for i, c in enumerate(nb.cells):
        if c.cell_type != "code":
            continue
        try:
            ast.parse(strip_magics(c.source))
        except SyntaxError as e:
            return f"cell {i}: {e}"
        if "### BEGIN SOLUTION" in c.source:
            return f"cell {i}: solution marker leaked into template"
    return None


def run_solution(path: Path, timeout: int) -> tuple[str, float, str]:
    nb = nbformat.read(path, as_version=4)
    client = NotebookClient(nb, timeout=timeout, kernel_name="python3",
                            resources={"metadata": {"path": str(path.parent)}})
    t0 = time.time()
    try:
        client.execute()
        status, detail = "pass", ""
    except CellExecutionError as e:
        status = "FAIL"
        detail = re.sub(r"\x1b\[[0-9;]*m", "", str(e)).strip().splitlines()[-1][:200]
    except Exception as e:  # timeouts, dead kernels
        status, detail = "FAIL", f"{type(e).__name__}: {e}"[:200]
    nbformat.write(nb, path)
    return status, time.time() - t0, detail


def main(args: list[str]) -> int:
    os.environ["PREP_NO_LOG"] = "1"  # kernels inherit this: verification never writes practice/log.csv
    timeout = 1800
    targets = [REPO / p for p in PARTS] if not args else [Path(a).resolve() for a in args]
    sols, tmpls = [], []
    for t in targets:
        if t.is_dir():
            part = t if (t / "solutions").is_dir() else t.parent
            sols += sorted((part / "solutions").glob("*.ipynb"))
            tmpls += sorted(part.glob("*.ipynb"))
        elif t.parent.name == "solutions":
            sols.append(t)
        else:
            tmpls.append(t)

    results = {}
    env = env_line()
    today = dt.date.today().isoformat()
    bad = 0
    for p in tmpls:
        err = check_template(p)
        key = str(p.relative_to(REPO))
        results[key] = {"kind": "template", "status": "FAIL" if err else "pass", "seconds": 0,
                      "detail": err or "", "date": today, "env": env}
        bad += bool(err)
        print(f"{'FAIL' if err else 'ok  '} template {key} {err or ''}")
    for p in sols:
        key = str(p.relative_to(REPO))
        status, secs, detail = run_solution(p, timeout)
        results[key] = {"kind": "solution", "status": status, "seconds": round(secs, 1),
                      "detail": detail, "date": today, "env": env}
        bad += status != "pass"
        print(f"{'ok  ' if status == 'pass' else 'FAIL'} solution {key} ({secs:.0f}s) {detail}")

    # merge under a lock: several verify runs may finish at the same time
    with open(STATE.with_suffix(".lock"), "w") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        state = json.loads(STATE.read_text()) if STATE.exists() else {}
        state.update(results)
        STATE.write_text(json.dumps(state, indent=1, sort_keys=True))
        write_report(state)
    print(f"\n{len(tmpls)} templates, {len(sols)} solutions, {bad} failures -> {REPORT.relative_to(REPO)}")
    return 1 if bad else 0


def write_report(state: dict) -> None:
    rows = sorted(state.items())
    lines = ["# Verification log", "",
             "Generated by `python tools/verify.py`. Solutions are executed end to end; "
             "templates are syntax-checked only (they raise `NotImplementedError` by design).", "",
             "| Notebook | Kind | Status | Runtime (s) | Date | Environment | Detail |",
             "| --- | --- | --- | --- | --- | --- | --- |"]
    for k, v in rows:
        lines.append(f"| `{k}` | {v['kind']} | {v['status']} | {v['seconds']} | {v['date']} | {v['env']} | "
                     f"{v['detail'].replace('|', '/')} |")
    REPORT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
